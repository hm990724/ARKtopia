const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const game=fs.readFileSync('src/components/Game.tsx','utf8');
const css=fs.readFileSync('src/app/globals.css','utf8');
const parsed=ts.createSourceFile('Game.tsx',game,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
assert.equal(parsed.parseDiagnostics.length,0,'Game.tsx must remain valid TSX');
assert(game.includes('const [captureReveal,setCaptureReveal]'),'capture reveal UI state must exist');
assert(game.includes('function confirmCaptureReveal()'),'player-controlled reveal transition');
assert(game.includes('setCaptureReveal({id:n.pending!,cell:command.cell??null,first:firstReturn})'),'hidden hunt must carry actual guessed coordinate into reveal');
assert(game.includes('setCaptureReveal({id:n.pending!,cell:null,first:firstReturn})'),'legacy tactical capture should also show visual feedback');
const pursuit=game.slice(game.indexOf('function onHuntAction('),game.indexOf('function rescue('));
assert(pursuit.includes('if(won){report(s,n,\'은신 개체 포획\');setCaptureReveal('),'successful search opens visual reveal');
assert(!pursuit.includes('if(won){report(s,n,\'은신 개체 포획\');dialogue('),'successful search must NOT immediately overlay dialogue');
assert(game.includes('{captureReveal&&s.pending===captureReveal.id&&!current'),'found-animal confirmation modal must render first');
assert(game.includes('className="v40-discovered-animal" src={img(captureReveal.id)}'),'revealed specimen must use existing species artwork');
assert(game.includes('onClick={confirmCaptureReveal}'),'reveal advances only with user acknowledgement');
assert(game.includes('{s.pending&&!captureReveal&&!aftermath'),'rescue choice must stay behind visual confirmation');
assert(css.includes('.v40-discovery-card')&&css.includes('@media(max-width:680px)'),'reveal styled for desktop and mobile');
console.log('PASS player sees species sprite and actual tile before dialogue or transport choices');
console.log('PASS first rabbit and subsequent species share the same capture presentation');
console.log('PASS transient reveal cannot corrupt saved game state; previous pending saves still open rescue');
